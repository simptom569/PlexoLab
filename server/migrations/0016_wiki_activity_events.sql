-- Прежние события страниц вики шли с типом `doc` и без проекта; теперь у них свой тип `wiki`.
-- Документы проекта (после 0014 у них всегда есть проект) остаются `doc`; на всякий случай их отличает та же подпись цели,
-- что и в 0014. Страница без названия подписана «Новая страница вики», поэтому по слову «Страница» вики не ищем.
-- Обратная миграция: server/migrations_down/0016_wiki_activity_events.down.sql

update activity set kind = 'wiki'
where kind = 'doc' and project_id is null and not (target like 'Документ «%' or target = 'Новый документ');
