import { describe, expect, it } from 'vitest'
import { syncDraft, type DraftState } from './useDraft'

const state = (value: string, draft: string): DraftState => ({ value, draft })

describe('syncDraft', () => {
  it('то же значение: ничего не меняется', () => {
    const s = state('Название', 'Название')
    expect(syncDraft(s, 'Название')).toBe(s)
    const edited = state('Название', 'Моя правка')
    expect(syncDraft(edited, 'Название')).toBe(edited)
  })

  it('в поле ничего не меняли: новое значение с сервера попадает в поле', () => {
    expect(syncDraft(state('Старое', 'Старое'), 'Чужая правка')).toEqual(state('Чужая правка', 'Чужая правка'))
  })

  it('человек печатает: чужая правка не стирает его текст, но становится новой основой', () => {
    expect(syncDraft(state('Старое', 'Моё недописанное'), 'Чужая правка')).toEqual(state('Чужая правка', 'Моё недописанное'))
  })

  it('и вторая, и третья чужая правка его текст не трогают', () => {
    let s = state('v1', 'мой текст')
    s = syncDraft(s, 'v2')
    s = syncDraft(s, 'v3')
    expect(s).toEqual(state('v3', 'мой текст'))
  })

  it('если чужая правка совпала с тем, что он набрал, расхождения нет', () => {
    expect(syncDraft(state('Старое', 'Новое'), 'Новое')).toEqual(state('Новое', 'Новое'))
  })

  it('своё сохранение: поле показывало то, что ушло на сервер, значение совпало — всё спокойно', () => {
    // после blur поле уже равно отправленному, значение с сервера приходит таким же
    expect(syncDraft(state('Старое', 'Новое'), 'Новое')).toEqual(state('Новое', 'Новое'))
  })

  it('сервер отклонил своё сохранение: значение вернулось, поле возвращается вместе с ним', () => {
    // поле показывало отправленное «Новое», основа успела стать «Новое» (оптимистичное обновление), потом откат
    let s = state('Старое', 'Новое')
    s = syncDraft(s, 'Новое') // оптимистично показали
    s = syncDraft(s, 'Старое') // сервер отказал
    expect(s).toEqual(state('Старое', 'Старое'))
  })

  it('сервер поправил отправленное (убрал лишние пробелы): поле берёт поправленное', () => {
    let s = state('Старое', 'Новое  ')
    s = syncDraft({ ...s, draft: 'Новое' }, 'Новое') // после blur поле стало «Новое»
    s = syncDraft(s, 'Новое!') // ответ сервера
    expect(s).toEqual(state('Новое!', 'Новое!'))
  })
})
